"""Generates name -> value accessors for a translated class, replacing GDScript's `obj.get(name)`
reflection in the trace comparisons (FighterCompare, AiCompare).

    python tools/gen_accessors.py --gd remake/core/fighter/fighter_state.gd --header src/core/fighter/fighter_state.h
        --cls FighterState --include core/fighter/fighter_state.h --func fighter_state_fields --out tests/support/x.cpp
        [--names a,b,c]

Names: `--names`, or every class-level `var` of the .gd (check_names.declared). A name whose header
declares `get_<name>()` (a GDScript property) is read through that getter. The generated table maps
each name to `field_value(obj.<name>)` (tests/support/field_value.h decides what counts as an int or
a move row, like `value is int` / `value is MoveRow`).
"""
import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from check_names import declared  # noqa: E402

VAR = re.compile(r"^(?:static\s+)?var\s+([A-Za-z_]\w*)")


def class_vars(gd_text: str) -> list[str]:
    """The class-level `var` names (not consts, funcs, enums or inner-class members)."""
    out = []
    for line in gd_text.splitlines():
        m = VAR.match(line)
        if m:
            out.append(m.group(1))
    return [n for n in out if n in declared(gd_text)]


def accessor(name: str, header: str) -> str:
    if re.search(rf"\bget_{re.escape(name)}\s*\(", header):
        return f"o.get_{name}()"
    return f"o.{name}"


def generate(gd_path: str, cls: str, include: str, func: str, names: list[str], header: str) -> str:
    rows = "\n".join(f'        {{"{n}", [](const t3::{cls}& o) {{ return field_value({accessor(n, header)}); }}}},' for n in names)
    return f"""// Generated by tools/gen_accessors.py from {gd_path}. Do not edit.
#include "{include}"
#include "support/field_value.h"

namespace t3test {{

const FieldTable<t3::{cls}>& {func}() {{
    static const FieldTable<t3::{cls}> table = {{
{rows}
    }};
    return table;
}}

}}  // namespace t3test
"""


def main() -> int:
    p = argparse.ArgumentParser()
    p.add_argument("--gd", type=Path, required=True)
    p.add_argument("--header", type=Path, required=True)
    p.add_argument("--cls", required=True)
    p.add_argument("--include", required=True)
    p.add_argument("--func", required=True)
    p.add_argument("--out", type=Path, required=True)
    p.add_argument("--names", default="")
    a = p.parse_args()
    gd_text = a.gd.read_text(encoding="utf-8")
    header = a.header.read_text(encoding="utf-8")
    names = [n for n in a.names.split(",") if n] or class_vars(gd_text)
    words = set(re.findall(r"\w+", header))
    missing = [n for n in names if n not in words and f"get_{n}" not in words]
    if missing:
        print("not in the header: " + ", ".join(missing))
        return 1
    a.out.write_text(generate(a.gd.as_posix(), a.cls, a.include, a.func, names, header), encoding="utf-8")
    print(f"{a.out}: {len(names)} fields")
    return 0


if __name__ == "__main__":
    sys.exit(main())
